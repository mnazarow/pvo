    callout(hx + 1, 63, 67, 57, "колонка из 5 отверстий — ОДНА точка:\nвсё, что воткнуто сюда, соединено", GREEN)
    callout(R - 10, 58.5, 67, 44, "канавка посередине:\nверхняя и нижняя половины\nмежду собой НЕ соединены", "#616161")

    rbox(ax, 5, 4, 93, 25, "#E3F2FD", ec="#64B5F6")
    txt(ax, 51.5, 24.5, "Правило, которое избавит от 90% ошибок новичка", 9, "#0D47A1", "bold")
