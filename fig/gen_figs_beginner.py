def new_ax(w, h):
    fig, ax = plt.subplots(figsize=(w, h))
    ax.set_xlim(0, 100); ax.set_ylim(0, 100)
    ax.axis("off"); fig.patch.set_facecolor("white")
    return fig, ax


def rbox(ax, x, y, w, h, fc, ec=None, lw=1.2, r=1.6, z=2):
    ax.add_patch(FancyBboxPatch((x, y), w, h,
                                boxstyle=f"round,pad=0,rounding_size={r}",
                                fc=fc, ec=ec or fc, lw=lw, zorder=z))


def arrow(ax, p1, p2, color="#444", lw=1.8, ls="-", z=5):
    ax.add_patch(FancyArrowPatch(p1, p2, arrowstyle="-|>", mutation_scale=14,
                                 color=color, lw=lw, linestyle=ls, zorder=z))


def txt(ax, x, y, s, size=8, color="#222222", weight="normal", ha="center", va="center", z=6):
    ax.text(x, y, s, fontsize=size, color=color, fontweight=weight, ha=ha, va=va, zorder=z)


def save(fig, name):
    p = os.path.join(OUT, name)
    fig.savefig(p, dpi=DPI, bbox_inches="tight", facecolor="white", pad_inches=0.12)
    plt.close(fig)
    from PIL import Image
    im = Image.open(p)
    if im.mode != "RGB":
        im.convert("RGB").save(p)
    print("ok", name)


