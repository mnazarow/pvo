const fs = require("fs");
const path = require("path");
const D = require("docx");

const FIG = p => path.join(__dirname, "fig", p);
const MONO = "Consolas";
const LINE = { line: 288, lineRule: D.LineRuleType.AUTO };

function pngSize(file) {
  const b = fs.readFileSync(file);
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
}

// ---------- помощники ----------
const P = (text, opts = {}) => new D.Paragraph({
  children: [new D.TextRun({ text, ...opts.run })],
  spacing: { after: 140, ...LINE }, alignment: D.AlignmentType.JUSTIFIED, ...opts.par,
});
const Pr = (runs, par = {}) => new D.Paragraph({
  children: runs, spacing: { after: 140, ...LINE }, alignment: D.AlignmentType.JUSTIFIED, ...par,
});
const R = (t, o = {}) => new D.TextRun({ text: t, ...o });
const Rb = (t, o = {}) => new D.TextRun({ text: t, bold: true, ...o });
const Ri = (t, o = {}) => new D.TextRun({ text: t, italics: true, ...o });
const Rc = (t, o = {}) => new D.TextRun({ text: t, font: MONO, ...o });

const H1 = t => new D.Paragraph({ heading: D.HeadingLevel.HEADING_1, children: [R(t)], pageBreakBefore: true });
const H1n = t => new D.Paragraph({ heading: D.HeadingLevel.HEADING_1, children: [R(t)] });
const H2 = t => new D.Paragraph({ heading: D.HeadingLevel.HEADING_2, children: [R(t)] });
const H3 = t => new D.Paragraph({ heading: D.HeadingLevel.HEADING_3, children: [R(t)] });

const Bullet = (x, level = 0) => new D.Paragraph({
  children: typeof x === "string" ? [R(x)] : x,
  numbering: { reference: "bul", level },
  spacing: { after: 90, line: 276, lineRule: D.LineRuleType.AUTO },
});
let stepInst = 0;
function Steps(items) {
  stepInst++;
  return items.map(it => new D.Paragraph({
    children: typeof it === "string" ? [R(it)] : it,
    numbering: { reference: "steps", level: 0, instance: stepInst },
    spacing: { after: 110, line: 276, lineRule: D.LineRuleType.AUTO },
  }));
}

function NoteBox(runs, kind = "info", title = null) {
  const fill = { warn: "FFF3CD", danger: "F8D7DA", info: "E3F2FD", ok: "E8F5E9", tip: "F3E5F5" }[kind];
  const bc = { warn: "E0A800", danger: "C82333", info: "64B5F6", ok: "66BB6A", tip: "AB47BC" }[kind];
  const bs = { style: D.BorderStyle.SINGLE, size: 6, color: bc };
  const kids = [];
  if (title) kids.push(new D.Paragraph({
    children: [Rb(title, { color: bc === "64B5F6" ? "0D47A1" : bc === "66BB6A" ? "1B5E20" : bc === "C82333" ? "721C24" : bc === "AB47BC" ? "4A148C" : "7A5A00", size: 21 })],
    spacing: { after: 60, ...LINE },
  }));
  kids.push(new D.Paragraph({
    children: typeof runs === "string" ? [R(runs)] : runs,
    spacing: { line: 276, lineRule: D.LineRuleType.AUTO },
  }));
  return new D.Table({
    columnWidths: [9750],
    rows: [new D.TableRow({ children: [new D.TableCell({
      width: { size: 9750, type: D.WidthType.DXA },
      shading: { type: D.ShadingType.CLEAR, fill },
      borders: { top: bs, bottom: bs, left: bs, right: bs },
      margins: { top: 140, bottom: 140, left: 180, right: 180 },
      children: kids,
    })] })],
  });
}

function Img(file, widthPx = 620, caption = null) {
  const { w, h } = pngSize(FIG(file));
  const out = [new D.Paragraph({
    alignment: D.AlignmentType.CENTER, spacing: { before: 140, after: caption ? 40 : 180 },
    children: [new D.ImageRun({ type: "png", data: fs.readFileSync(FIG(file)),
      transformation: { width: widthPx, height: Math.round(widthPx * h / w) } })],
  })];
  if (caption) out.push(new D.Paragraph({
    alignment: D.AlignmentType.CENTER, spacing: { after: 220 },
    children: [R(caption, { italics: true, size: 18, color: "555555" })],
  }));
  return out;
}

function Tbl(headers, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  const mk = (c, head, wdx) => new D.TableCell({
    width: { size: wdx, type: D.WidthType.DXA },
    shading: head ? { type: D.ShadingType.CLEAR, fill: "00575C" } : undefined,
    margins: { top: 70, bottom: 70, left: 110, right: 110 },
    children: [new D.Paragraph({
      children: typeof c === "string"
        ? [R(c, head ? { bold: true, color: "FFFFFF", size: 19 } : { size: 20 })] : c,
      spacing: { line: 264, lineRule: D.LineRuleType.AUTO },
    })],
  });
  return new D.Table({
    columnWidths: widths, width: { size: total, type: D.WidthType.DXA },
    rows: [
      new D.TableRow({ tableHeader: true, children: headers.map((x, i) => mk(x, true, widths[i])) }),
      ...rows.map(r => new D.TableRow({ children: r.map((c, i) => mk(c, false, widths[i])) })),
    ],
  });
}

function Code(lines) {
  return lines.map(l => new D.Paragraph({
    children: [Rc(l, { size: 19 })],
    shading: { type: D.ShadingType.CLEAR, fill: "F2F2F2" },
    spacing: { after: 0, line: 252, lineRule: D.LineRuleType.AUTO }, indent: { left: 260 },
  }));
}

// Параметр «человеческим языком»
function Par(name, def, plain, feel, examples, advice) {
  const out = [];
  out.push(new D.Paragraph({
    spacing: { before: 240, after: 70 },
    border: { bottom: { style: D.BorderStyle.SINGLE, size: 4, color: "9FB6B8" } },
    children: [Rc(name, { bold: true, size: 23, color: "00575C" }),
               R("     по умолчанию ", { size: 19, color: "666666" }),
               Rc(def, { size: 21, bold: true, color: "333333" })],
  }));
  out.push(Pr([Rb("Простыми словами. "), R(plain)]));
  out.push(Pr([Rb("Что вы заметите. "), R(feel)]));
  examples.forEach(e => out.push(Bullet([Rb("Если "), R(e)])));
  out.push(Pr([Rb("Совет. "), R(advice)]));
  return out;
}

