const fs = require("fs");
const path = require("path");
const D = require("docx");

const FIG = p => path.join(__dirname, "fig", p);
const MONO = "Consolas";

function pngSize(file) {
  const b = fs.readFileSync(file);
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
}

// ---------- помощники ----------
const P = (text, opts = {}) => new D.Paragraph({
  children: [new D.TextRun({ text, ...opts.run })],
  spacing: { after: 120, line: 276, lineRule: D.LineRuleType.AUTO }, alignment: D.AlignmentType.JUSTIFIED, ...opts.par,
});
const Prich = (runs, par = {}) => new D.Paragraph({
  children: runs, spacing: { after: 120, line: 276, lineRule: D.LineRuleType.AUTO }, alignment: D.AlignmentType.JUSTIFIED, ...par,
});
const R = (text, o = {}) => new D.TextRun({ text, ...o });
const Rb = (text, o = {}) => new D.TextRun({ text, bold: true, ...o });
const Rc = (text, o = {}) => new D.TextRun({ text, font: MONO, ...o });

const H1 = t => new D.Paragraph({ heading: D.HeadingLevel.HEADING_1, children: [R(t)], pageBreakBefore: true });
const H1n = t => new D.Paragraph({ heading: D.HeadingLevel.HEADING_1, children: [R(t)] });
const H2 = t => new D.Paragraph({ heading: D.HeadingLevel.HEADING_2, children: [R(t)] });
const H3 = t => new D.Paragraph({ heading: D.HeadingLevel.HEADING_3, children: [R(t)] });

const Bullet = (runsOrText, level = 0) => new D.Paragraph({
  children: typeof runsOrText === "string" ? [R(runsOrText)] : runsOrText,
  numbering: { reference: "bul", level }, spacing: { after: 80, line: 264, lineRule: D.LineRuleType.AUTO },
});
let stepInstance = 0;
function Steps(items) { // нумерованные шаги, счёт с 1 в каждом списке
  stepInstance++;
  return items.map(it => new D.Paragraph({
    children: typeof it === "string" ? [R(it)] : it,
    numbering: { reference: "steps", level: 0, instance: stepInstance },
    spacing: { after: 90, line: 264, lineRule: D.LineRuleType.AUTO },
  }));
}

function NoteBox(text, kind = "warn") { // цветная врезка
  const fill = { warn: "FFF3CD", danger: "F8D7DA", info: "D6E9F8", ok: "DFF0D8" }[kind];
  const border = { warn: "E0A800", danger: "C82333", info: "3E7CB1", ok: "4CAE4C" }[kind];
  const bs = { style: D.BorderStyle.SINGLE, size: 6, color: border };
  return new D.Table({
    columnWidths: [9750],
    rows: [new D.TableRow({ children: [new D.TableCell({
      width: { size: 9750, type: D.WidthType.DXA },
      shading: { type: D.ShadingType.CLEAR, fill },
      borders: { top: bs, bottom: bs, left: bs, right: bs },
      margins: { top: 120, bottom: 120, left: 160, right: 160 },
      children: [new D.Paragraph({ children: typeof text === "string" ? [R(text)] : text, spacing: { line: 264, lineRule: D.LineRuleType.AUTO } })],
    })] })],
  });
}

function Img(file, widthPx = 600, caption = null) {
  const { w, h } = pngSize(FIG(file));
  const height = Math.round(widthPx * h / w);
  const out = [new D.Paragraph({
    alignment: D.AlignmentType.CENTER, spacing: { before: 120, after: caption ? 40 : 160 },
    children: [new D.ImageRun({ type: "png", data: fs.readFileSync(FIG(file)), transformation: { width: widthPx, height } })],
  })];
  if (caption) out.push(new D.Paragraph({
    alignment: D.AlignmentType.CENTER, spacing: { after: 200 },
    children: [R(caption, { italics: true, size: 18, color: "555555" })],
  }));
  return out;
}

function Tbl(headers, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  const mkCell = (content, head = false, wdx) => new D.TableCell({
    width: { size: wdx, type: D.WidthType.DXA },
    shading: head ? { type: D.ShadingType.CLEAR, fill: "00575C" } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [new D.Paragraph({
      children: typeof content === "string"
        ? [R(content, head ? { bold: true, color: "FFFFFF", size: 19 } : { size: 20 })] : content,
      spacing: { line: 252, lineRule: D.LineRuleType.AUTO },
    })],
  });
  return new D.Table({
    columnWidths: widths,
    width: { size: total, type: D.WidthType.DXA },
    rows: [
      new D.TableRow({ tableHeader: true, children: headers.map((hh, i) => mkCell(hh, true, widths[i])) }),
      ...rows.map(r => new D.TableRow({ children: r.map((c, i) => mkCell(c, false, widths[i])) })),
    ],
  });
}

function Code(lines) {
  return lines.map(l => new D.Paragraph({
    children: [Rc(l, { size: 18 })],
    shading: { type: D.ShadingType.CLEAR, fill: "F2F2F2" },
    spacing: { after: 0, line: 240, lineRule: D.LineRuleType.AUTO }, indent: { left: 220 },
  }));
}

// Блок подробного описания параметра
function Param(name, def, what, range, examples, recom) {
  const out = [];
  out.push(new D.Paragraph({
    spacing: { before: 220, after: 60 },
    border: { bottom: { style: D.BorderStyle.SINGLE, size: 4, color: "9FB6B8" } },
    children: [Rc(name, { bold: true, size: 22, color: "00575C" }),
               R("      по умолчанию: ", { size: 19, color: "666666" }),
               Rc(def, { size: 20, bold: true, color: "333333" })],
  }));
  out.push(Prich([Rb("Что делает. "), R(what)]));
  out.push(Prich([Rb("Диапазон. "), R(range)]));
  examples.forEach(e => out.push(Bullet([Rb("Пример: "), R(e)])));
  out.push(Prich([Rb("Рекомендации. "), R(recom)]));
  return out;
}

