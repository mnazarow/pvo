const laserNote = NoteBox(
[Rb("Лазерная безопасность: ", { color: "721C24" }),
  R("только модуль ≤5 мВт (KY-008). Не ставьте турель на уровне глаз, ограничьте сектор так, чтобы луч не выходил в проёмы и окна. Лазеры «burning/engraving» устанавливать запрещено — необратимая травма зрения.")], "danger");

function cover(children, title, subtitle) {
  children.push(
    new D.Paragraph({ spacing: { before: 200, after: 60 }, alignment: D.AlignmentType.CENTER,
      children: [R("ПВО ОТ КОМАРОВ", { bold: true, size: 40, color: "00575C" })] }),
    new D.Paragraph({ alignment: D.AlignmentType.CENTER, spacing: { after: 40 },
      children: [R(title, { bold: true, size: 30, color: "1B6E75" })] }),
    new D.Paragraph({ alignment: D.AlignmentType.CENTER, spacing: { after: 200 },
      children: [R(subtitle + " · версия 1.0 · август 2026", { size: 20, italics: true, color: "666666" })] }),
    laserNote,
    optNote,
    P(""),
  );
}

