function makeDoc(children, title) {
  return new D.Document({
    creator: "PVO project", title,
    styles: { default: {
      document: { run: { font: "Calibri", size: 21 }, paragraph: { spacing: LINE } },
      heading1: { run: { font: "Calibri", size: 30, bold: true, color: "00575C" },
                  paragraph: { spacing: { before: 300, after: 160 } } },
      heading2: { run: { font: "Calibri", size: 25, bold: true, color: "1B6E75" },
                  paragraph: { spacing: { before: 240, after: 130 } } },
    } },
    numbering: { config: [
      { reference: "bul", levels: [{ level: 0, format: D.LevelFormat.BULLET, text: "•",
        alignment: D.AlignmentType.LEFT, style: { paragraph: { indent: { left: 460, hanging: 230 } } } }] },
      { reference: "steps", levels: [{ level: 0, format: D.LevelFormat.DECIMAL, text: "%1.",
        alignment: D.AlignmentType.LEFT, style: { paragraph: { indent: { left: 500, hanging: 300 } } } }] },
    ] },
    sections: [{ properties: { page: { margin: { top: 1134, bottom: 1134, left: 1418, right: 1134 } } },
      footers: { default: new D.Footer({ children: [new D.Paragraph({ alignment: D.AlignmentType.CENTER,
        children: [new D.TextRun({ children: [D.PageNumber.CURRENT], size: 18, color: "777777" })] })] }) },
      children }],
  });
}

