// Четыре руководства по сборке: «Сборка варианта A/B/C/D» (.docx)
const fs = require("fs");
const path = require("path");
const D = require("docx");

const FIG = p => path.join(__dirname, "fig", p);
const MONO = "Consolas";
function pngSize(f) { const b = fs.readFileSync(f); return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) }; }

const LINE = { line: 276, lineRule: D.LineRuleType.AUTO };
const P = (t, o = {}) => new D.Paragraph({ children: [new D.TextRun({ text: t, ...o.run })],
  spacing: { after: 120, ...LINE }, alignment: D.AlignmentType.JUSTIFIED, ...o.par });
const Pr = (runs, par = {}) => new D.Paragraph({ children: runs,
  spacing: { after: 120, ...LINE }, alignment: D.AlignmentType.JUSTIFIED, ...par });
const R = (t, o = {}) => new D.TextRun({ text: t, ...o });
const Rb = (t, o = {}) => new D.TextRun({ text: t, bold: true, ...o });
const Rc = (t, o = {}) => new D.TextRun({ text: t, font: MONO, ...o });
const H1 = t => new D.Paragraph({ heading: D.HeadingLevel.HEADING_1, children: [R(t)] });
const H2 = t => new D.Paragraph({ heading: D.HeadingLevel.HEADING_2, children: [R(t)] });

const Bullet = x => new D.Paragraph({ children: typeof x === "string" ? [R(x)] : x,
  numbering: { reference: "bul", level: 0 }, spacing: { after: 80, line: 264, lineRule: D.LineRuleType.AUTO } });
let stepInst = 0;
const Steps = items => { stepInst++; return items.map(it => new D.Paragraph({
  children: typeof it === "string" ? [R(it)] : it,
  numbering: { reference: "steps", level: 0, instance: stepInst },
  spacing: { after: 90, line: 264, lineRule: D.LineRuleType.AUTO } })); };

function NoteBox(runs, kind = "warn") {
  const fill = { warn: "FFF3CD", danger: "F8D7DA", info: "D6E9F8", ok: "DFF0D8" }[kind];
  const bc = { warn: "E0A800", danger: "C82333", info: "3E7CB1", ok: "4CAE4C" }[kind];
  const bs = { style: D.BorderStyle.SINGLE, size: 6, color: bc };
  return new D.Table({ columnWidths: [9750], rows: [new D.TableRow({ children: [new D.TableCell({
    width: { size: 9750, type: D.WidthType.DXA },
    shading: { type: D.ShadingType.CLEAR, fill },
    borders: { top: bs, bottom: bs, left: bs, right: bs },
    margins: { top: 120, bottom: 120, left: 160, right: 160 },
    children: [new D.Paragraph({ children: typeof runs === "string" ? [R(runs)] : runs, spacing: { line: 264, lineRule: D.LineRuleType.AUTO } })],
  })] })] });
}

function Img(file, widthPx = 600, caption = null) {
  const { w, h } = pngSize(FIG(file));
  const out = [new D.Paragraph({ alignment: D.AlignmentType.CENTER,
    spacing: { before: 120, after: caption ? 40 : 160 },
    children: [new D.ImageRun({ type: "png", data: fs.readFileSync(FIG(file)),
      transformation: { width: widthPx, height: Math.round(widthPx * h / w) } })] })];
  if (caption) out.push(new D.Paragraph({ alignment: D.AlignmentType.CENTER, spacing: { after: 200 },
    children: [R(caption, { italics: true, size: 18, color: "555555" })] }));
  return out;
}

function Tbl(headers, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  const mk = (c, head, wdx) => new D.TableCell({
    width: { size: wdx, type: D.WidthType.DXA },
    shading: head ? { type: D.ShadingType.CLEAR, fill: "00575C" } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [new D.Paragraph({ children: typeof c === "string"
      ? [R(c, head ? { bold: true, color: "FFFFFF", size: 19 } : { size: 20 })] : c,
      spacing: { line: 252, lineRule: D.LineRuleType.AUTO } })] });
  return new D.Table({ columnWidths: widths, width: { size: total, type: D.WidthType.DXA },
    rows: [new D.TableRow({ tableHeader: true, children: headers.map((x, i) => mk(x, true, widths[i])) }),
      ...rows.map(r => new D.TableRow({ children: r.map((c, i) => mk(c, false, widths[i])) }))] });
}

