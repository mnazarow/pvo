def cell(r, c, v, *, bold=False, size=10, color="000000", fill=None, wrap=True,
         center=False, fmt=None, italic=False):
    cl = ws.cell(row=r, column=c, value=v)
    cl.font = Font(name="Arial", size=size, bold=bold, color=color, italic=italic)
    cl.alignment = Alignment(vertical="center", wrap_text=wrap,
                             horizontal="center" if center else "left")
    if fill:
        cl.fill = PatternFill("solid", fgColor=fill)
    if fmt:
        cl.number_format = fmt
    cl.border = border
    return cl

